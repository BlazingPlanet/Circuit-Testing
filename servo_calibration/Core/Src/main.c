/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM3_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */

  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);
  set_pwm(0, START_US);
  set_pwm(1, START_US);
  uart_print("\r\nServo cal ready. a <us>, b <us>, c = center, ? = status\r\n");
  uint32_t last_ramp = HAL_GetTick();

  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED2);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint8_t c;
    if (HAL_UART_Receive(&huart2, &c, 1, 1) == HAL_OK) {
      if (c == '\r' || c == '\n') {
        if (line_len > 0) {
          uart_print("\r\n");
          line[line_len] = '\0';
          handle_line(line);
          line_len = 0;
        }
      } else if ((c == 0x08 || c == 0x7F) && line_len > 0) {
        line_len--;
        uart_print("\b \b");
      } else if (line_len < sizeof(line) - 1 && c >= 0x20 && c < 0x7F) {
        line[line_len++] = c;
        HAL_UART_Transmit(&huart2, &c, 1, HAL_MAX_DELAY);  // echo what you type
      }
    }

    if (HAL_GetTick() - last_ramp >= RAMP_PERIOD_MS) {
      last_ramp = HAL_GetTick();
      for (int i = 0; i < 2; i++) {
        if (current[i] < target[i])
          current[i] = (target[i] - current[i] > RAMP_STEP_US) ? current[i] + RAMP_STEP_US : target[i];
        else if (current[i] > target[i])
          current[i] = (current[i] - target[i] > RAMP_STEP_US) ? current[i] - RAMP_STEP_US : target[i];
        set_pwm(i, current[i]);
      }
    }
  }
  
  /* USER CODE END 3 */
}

